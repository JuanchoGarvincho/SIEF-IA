-- =====================================================================
-- ESQUEMA SIEF_IA PARA POSTGRESQL (Render)
-- Traducido desde la base local de SQL Server (13 tablas).
-- Los nombres pasan de PascalCase a snake_case para no tener que usar comillas:
--   dbo.ProgramaAcademico.IdPrograma  ->  programa_academico.id_programa
-- Se agregan las columnas que el backend necesita y la BD local no tenía:
--   estudiante/jurado: correo, clave_hash (login)   proyecto: categoria
-- Es seguro ejecutarlo varias veces (IF NOT EXISTS).
-- =====================================================================

CREATE TABLE IF NOT EXISTS estado (
  id_estado           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_estado       VARCHAR(50) NOT NULL,
  fecha_registro      TIMESTAMP DEFAULT now(),
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS facultad (
  id_facultad         INT PRIMARY KEY,
  id_estado           INT DEFAULT 1 REFERENCES estado(id_estado),
  nombre_facultad     VARCHAR(100) NOT NULL,
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS programa_academico (
  id_programa         INT PRIMARY KEY,
  id_facultad         INT REFERENCES facultad(id_facultad),
  id_estado           INT DEFAULT 1 REFERENCES estado(id_estado),
  nombre_programa     VARCHAR(100) NOT NULL,
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rol_usuario (
  id_rol              INT PRIMARY KEY,
  id_estado           INT DEFAULT 1 REFERENCES estado(id_estado),
  nombre_rol          VARCHAR(50) NOT NULL,
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS materia (
  id_materia          INT PRIMARY KEY,
  id_estado           INT DEFAULT 1 REFERENCES estado(id_estado),
  nombre_materia      VARCHAR(100) NOT NULL,
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ubicacion (
  id_ubicacion        INT PRIMARY KEY,
  id_estado           INT DEFAULT 1 REFERENCES estado(id_estado),
  nomenclatura_salon  VARCHAR(50),
  stand               VARCHAR(20) UNIQUE,
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS estudiante (
  id_estudiante       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cedula_estudiante   VARCHAR(20) NOT NULL UNIQUE,
  id_programa         INT,
  id_rol              INT,
  id_estado           INT DEFAULT 1,
  nombre_completo     VARCHAR(100) NOT NULL CHECK (length(trim(nombre_completo)) > 0),
  fecha_matricula     TIMESTAMP DEFAULT now(),
  fecha_actualizacion TIMESTAMP DEFAULT now(),
  correo              VARCHAR(160) UNIQUE,
  clave_hash          VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS jurado (
  id_jurado           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cedula_jurado       VARCHAR(20) NOT NULL UNIQUE,
  id_facultad         INT,
  id_rol              INT,
  id_estado           INT DEFAULT 1,
  nombre_completo     VARCHAR(100) NOT NULL,
  especialidad        VARCHAR(80),
  fecha_actualizacion TIMESTAMP DEFAULT now(),
  correo              VARCHAR(160) UNIQUE,
  clave_hash          VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS proyecto (
  id_proyecto         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_materia          INT REFERENCES materia(id_materia),
  id_ubicacion        INT REFERENCES ubicacion(id_ubicacion),
  id_estado           INT DEFAULT 1 REFERENCES estado(id_estado),
  titulo              VARCHAR(150) NOT NULL CHECK (length(trim(titulo)) > 0),
  resumen_tecnico     TEXT,
  pregunta_ia_1       VARCHAR(255),
  pregunta_ia_2       VARCHAR(255),
  pregunta_ia_3       VARCHAR(255),
  fecha_actualizacion TIMESTAMP DEFAULT now(),
  id_estudiante       INT REFERENCES estudiante(id_estudiante),
  categoria           VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS evaluacion (
  id_evaluacion       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proyecto         INT REFERENCES proyecto(id_proyecto),
  id_estado           INT DEFAULT 1 REFERENCES estado(id_estado),
  nota_rapida         TEXT,
  feedback_ia         TEXT,
  fecha_actualizacion TIMESTAMP DEFAULT now(),
  id_jurado           INT REFERENCES jurado(id_jurado),
  -- Un jurado califica un proyecto una sola vez (NULLs se permiten varias veces)
  CONSTRAINT uq_evaluacion_jurado_proyecto UNIQUE (id_jurado, id_proyecto)
);

CREATE TABLE IF NOT EXISTS detalle_nota (
  id_detalle          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evaluacion       INT REFERENCES evaluacion(id_evaluacion) ON DELETE CASCADE,
  criterio_evaluado   VARCHAR(50),
  puntaje             NUMERIC(3,1) CHECK (puntaje BETWEEN 1.0 AND 5.0),
  fecha_actualizacion TIMESTAMP DEFAULT now(),
  CONSTRAINT uq_detalle_evaluacion_criterio UNIQUE (id_evaluacion, criterio_evaluado)
);

CREATE TABLE IF NOT EXISTS consentimiento_dato (
  id_consentimiento   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cedula_titular      VARCHAR(20) NOT NULL,
  fecha_autorizacion  TIMESTAMP DEFAULT now(),
  ip_registro         VARCHAR(50),
  finalidad_aceptada  VARCHAR(255),
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS auditoria_acceso (
  id_auditoria        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cedula_usuario      VARCHAR(20) NOT NULL,
  fecha_acceso        TIMESTAMP DEFAULT now(),
  modulo_visitado     VARCHAR(100),
  accion_realizada    VARCHAR(100),
  fecha_actualizacion TIMESTAMP DEFAULT now()
);

-- Equivalente al trigger TR_Evaluacion_UpdateFecha de SQL Server
CREATE OR REPLACE FUNCTION fn_actualizar_fecha() RETURNS trigger AS $$
BEGIN
  NEW.fecha_actualizacion := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_evaluacion_update_fecha ON evaluacion;
CREATE TRIGGER tr_evaluacion_update_fecha BEFORE UPDATE ON evaluacion
  FOR EACH ROW EXECUTE FUNCTION fn_actualizar_fecha();
